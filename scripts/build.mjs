import fs from 'node:fs';
const root = new URL('../', import.meta.url);
const modules = ['parser', 'transport', 'normalize', 'selection'];
const output = '// Generated by npm run build. Edit lib/ instead.\n' + modules.map(name =>
  fs.readFileSync(new URL(`lib/${name}.js`, root), 'utf8')
    .replace(/^import .*;\n/gm, '').replace(/^export /gm, '')
).join('\n');
const target = new URL('src/generated/core.js', root);
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== output) throw new Error('Generated core is stale: run npm run build');
} else {
  fs.writeFileSync(target, output);
}
